pub(crate) mod transform;
pub(crate) mod validate;

#[derive(Debug, PartialEq, Eq, Hash, Clone, Copy, PartialOrd, Ord)]
pub(crate) enum RequestHandlerMethod {
  Get,
  Post,
  Put,
  Delete,
  Patch,
  Options,
}

#[derive(Debug, PartialEq, Eq, Hash, Clone, Copy, PartialOrd, Ord)]
pub(crate) enum FormActionMethod {
  Get,
  Post,
  Put,
  Delete,
  Patch,
}

pub(super) struct LocalHandlerIdentGenerator {
  action_counter: usize,
  event_counter: usize,
}

impl Default for LocalHandlerIdentGenerator {
  fn default() -> Self {
    Self {
      action_counter: 0,
      event_counter: 0,
    }
  }
}

pub(super) const ACTION_DECL_PREFIX: &str = "_action$";
pub(super) const EVENT_DECL_PREFIX: &str = "_handler$";

fn action_ident(method: FormActionMethod, index: usize) -> String {
  format!(
    "{}{}${}",
    ACTION_DECL_PREFIX,
    format!("{:?}", method).to_lowercase(),
    index
  )
}

fn event_ident(index: usize) -> String {
  format!("{}{}", EVENT_DECL_PREFIX, index)
}

impl LocalHandlerIdentGenerator {
  pub(super) fn next_action_ident(&mut self, method: FormActionMethod) -> String {
    let export_name = action_ident(method, self.action_counter);
    self.action_counter += 1;
    export_name
  }

  pub(super) fn next_event_ident(&mut self) -> String {
    let export_name = event_ident(self.event_counter);
    self.event_counter += 1;
    export_name
  }
}

/// A form action or event handler export name generated by [`LocalHandlerIdentGenerator`], with
/// the value of the counter it was generated with.
pub(super) enum HandlerIdent {
  Action(FormActionMethod, usize),
  Event(usize),
}

/// The inverse of [`LocalHandlerIdentGenerator`]; returns `None` for every other name.
pub(super) fn parse_handler_ident(name: &str) -> Option<HandlerIdent> {
  let ident = if let Some(rest) = name.strip_prefix(ACTION_DECL_PREFIX) {
    let (method, index) = rest.split_once('$')?;
    let method = match method {
      "get" => FormActionMethod::Get,
      "post" => FormActionMethod::Post,
      "put" => FormActionMethod::Put,
      "delete" => FormActionMethod::Delete,
      "patch" => FormActionMethod::Patch,
      _ => return None,
    };
    HandlerIdent::Action(method, index.parse().ok()?)
  } else {
    HandlerIdent::Event(name.strip_prefix(EVENT_DECL_PREFIX)?.parse().ok()?)
  };

  // rejects names that only parse leniently, e.g. with leading zeros
  let generated = match ident {
    HandlerIdent::Action(method, index) => action_ident(method, index),
    HandlerIdent::Event(index) => event_ident(index),
  };
  (generated == name).then_some(ident)
}
